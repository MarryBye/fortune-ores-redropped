# -*- coding: utf-8 -*-
"""Silhouette library for the ore-chunk item textures.

Every form is a 16x16 grid of single characters:

    .  transparent
    #  body            (auto-shaded from the material ramp)
    +  body, forced one step lighter
    ,  body, forced one step darker
    ^  body, forced specular highlight
    -  internal facet edge (drawn dark, never merged with the outline)
    o  rock matrix      (grey ramp)
    *  accent           (secondary ramp, e.g. glowing specks or a second mineral)

The outline is derived from the silhouette by the renderer, so a form only has to
describe shape - which is the whole point: no two ores should share one.
"""

FORMS = {}


def form(name, art):
    rows = art.strip("\n").split("\n")
    assert len(rows) == 16, "%s: %d rows" % (name, len(rows))
    for i, r in enumerate(rows):
        assert len(r) == 16, "%s: row %d is %d chars (%r)" % (name, i, len(r), r)
    assert name not in FORMS, "duplicate form %s" % name
    FORMS[name] = rows


